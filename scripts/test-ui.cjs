// Smoke-Test der mobilen und Desktop-Oberfläche ohne echten Migros-Webzugriff.
const fs=require('node:fs');
const assert=require('node:assert/strict');
const {JSDOM}=require('jsdom');
const html=fs.readFileSync('index.html','utf8');
const dom=new JSDOM(html,{url:'https://mherfurthhtm.github.io/family-food-planner/',runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window;
const select=s=>w.document.querySelector(s);
const count=s=>w.document.querySelectorAll(s).length;
const click=s=>{const e=select(s);assert.ok(e,'Element fehlt: '+s);e.click();};
w.scrollTo=()=>{};
w.fetch=async()=>({ok:true,json:async()=>JSON.parse(fs.readFileSync('migros-prices.json','utf8'))});
for(const path of ['cookbooks.js','hearty-extra.js','fitness-extra.js'])w.eval(fs.readFileSync(path,'utf8'));
const inline=html.match(/<script>\s*([\s\S]*?)<\/script>/);
assert.ok(inline,'Hauptprogramm fehlt');
w.eval(inline[1]);
(async()=>{
 await new Promise(ok=>setTimeout(ok,50));
 assert.equal(count('.mobile-nav-item'),4,'Vier mobile Hauptpunkte');
 assert.equal(count('.day-select'),7,'Sieben auswählbare Tage');
 assert.equal(count('.day-grid .day-card'),1,'Anfangs genau ein Tag');
 assert.ok(select('.hero-price').textContent.includes('CHF'));
 assert.equal(w.FamilyFoodPlanner.recipes.length,167,'Rezeptdaten bleiben erhalten');
 const before=w.FamilyFoodPlanner.getState();
 click('.day-select[data-day="2"]');
 assert.equal(count('.day-grid .day-card'),1,'Wechsel auf einzelnen Tag');
 assert.ok(select('.day-grid .day-card').textContent.includes('Mittwoch'));
 click('[data-action="toggle-week"]');
 assert.equal(count('.day-grid .day-card'),7,'Alle sieben Tage können angezeigt werden');
 click('.mobile-nav-item[data-view="list"]');
 assert.ok(count('details.category')>3,'Gruppierte Einkaufsliste sichtbar');
 assert.ok(count('.product-row')>0,'Einkaufsprodukte sichtbar');
 assert.ok(count('.category[open]')>=1,'Mindestens eine Einkaufskategorie geöffnet');
 const input=select('input[data-action="check"]');
 assert.ok(input,'Einkauf abhaken möglich');
 const key=input.dataset.key;
 input.checked=true;
 input.dispatchEvent(new w.Event('change',{bubbles:true}));
 assert.equal(w.FamilyFoodPlanner.getState().checked[key],true,'Abhaken bleibt gespeichert');
 click('.mobile-nav-item[data-view="nutrition"]');
 assert.ok(select('#nutrition-person'),'Ernährungstagebuch erreichbar');
 click('.mobile-nav-item[data-view="more"]');
 assert.equal(count('.more-link'),2,'Mehr-Bereich mit zwei Zielen');
 click('.more-link[data-view="books"]');
 assert.equal(count('.cookbook-collection'),2,'Zwei Kochbücher verfügbar');
 assert.equal(count('.cookbook-collection[open]'),0,'Kochbücher anfangs eingeklappt');
 click('.cookbook-collection summary');
 assert.ok(count('.cookbook-collection[open]')>=1,'Kochbuch aufklappbar');
 click('.mobile-nav-item[data-view="more"]');
 click('.more-link[data-view="settings"]');
 assert.ok(select('#settings-form'),'Einstellungen erreichbar');
 click('.mobile-nav-item[data-view="plan"]');
 assert.equal(count('.day-select'),7,'Rückkehr zum Wochenplan');
 const after=w.FamilyFoodPlanner.getState();
 assert.equal(after.config.people,before.config.people,'Personenzahl unverändert');
 assert.equal(after.config.budget,before.config.budget,'Budget unverändert');
 console.log('OK: 167 Rezepte, Tagesnavigation, Wochenansicht, Einkaufsliste, Checkliste, Tagebuch, Kochbücher und Einstellungen.');
 w.close();
})().catch(e=>{console.error(e);process.exitCode=1;w.close()});
